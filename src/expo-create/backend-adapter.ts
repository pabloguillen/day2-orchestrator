import type { ProductPlan } from "./types";

/**
 * The new app's backend adapter (src/backend/ in the app), written by day2
 * before the backend step. The app talks to one small typed interface, so
 * where the data lives can change without touching the screens
 * (docs/expo-apps.md, "Hosting"):
 *
 *   types.ts    the plan's data model
 *   adapter.ts  the Backend interface (collections, auth, server functions)
 *   local.ts    an in-memory implementation (optionally persisted on the
 *               device), so the app runs and the device checks pass today
 *   hosted.ts   the hosted implementation: supabase-js against day2's
 *               Supabase project when the app is hosted (the build agent
 *               writes it), else a TODO
 *   index.ts    the one place that picks the implementation: hosted when
 *               EXPO_PUBLIC_SUPABASE_URL and _KEY are set, in memory in
 *               tests and without them
 *
 * The build agent refines the field types and wires the screens to it.
 */

const pascal = (s: string) =>
  s
    .replace(/[^A-Za-z0-9]+/g, " ")
    .trim()
    .split(" ")
    .filter(Boolean)
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join("") || "Item";
const camel = (s: string) => {
  const p = pascal(s);
  return p[0]!.toLowerCase() + p.slice(1);
};
const field = (s: string) => {
  const c = camel(s);
  return /^[A-Za-z_]/.test(c) ? c : `f${c}`;
};
const plural = (s: string) => (/(s|x|ch|sh)$/.test(s) ? `${s}es` : /[^aeiou]y$/.test(s) ? `${s.slice(0, -1)}ies` : `${s}s`);

export type Entity = { type: string; collection: string; fields: string[]; where: "device" | "server" };

/** Pure. The plan's data as entities with valid TypeScript names. */
export function entities(plan: Pick<ProductPlan, "data">): Entity[] {
  const seen = new Set<string>();
  const out: Entity[] = [];
  for (const d of plan.data) {
    const type = pascal(d.name);
    if (seen.has(type)) continue;
    seen.add(type);
    const fields = [...new Set(d.fields.map(field))].filter((f) => f !== "id");
    out.push({ type, collection: plural(camel(d.name)), fields, where: d.where });
  }
  return out;
}

/** Pure. The adapter's files, keyed by their path in the app. */
export function backendAdapterFiles(plan: Pick<ProductPlan, "data" | "accounts" | "functions">, o: { hosted?: boolean } = {}): Record<string, string> {
  const ents = entities(plan);
  const fns = [...new Map((plan.functions ?? []).map((f) => [camel(f.name), f])).entries()];
  const names = [...ents.map((e) => e.type), ...(plan.accounts ? ["User"] : [])];
  const typeImport = names.length ? [`import type { ${names.join(", ")} } from "./types";`] : [];
  const types = [
    "// The app's data model, from the approved plan. Generated by day2; refine the field types here.",
    "",
    ...ents.flatMap((e) => [
      `/** Stored ${e.where === "device" ? "on the device" : o.hosted ? "on the server (day2's hosted backend)" : "on the server once the app is hosted"}. */`,
      `export type ${e.type} = {`,
      "  id: string;",
      ...e.fields.map((f) => `  ${f}: string; // TODO(day2 build agent): the real type`),
      "};",
      "",
    ]),
    ...(plan.accounts ? ["export type User = { id: string; email: string; name?: string };", ""] : []),
    "export {};",
    "",
  ].join("\n");

  const adapter = [
    "// The one interface the app uses for data, accounts and server work.",
    "// Every implementation (local.ts in memory, hosted.ts on day2's hosted",
    "// backend) implements exactly this; the screens only ever see this.",
    "",
    ...typeImport,
    "",
    "export type Collection<T extends { id: string }> = {",
    "  list(): Promise<T[]>;",
    "  get(id: string): Promise<T | null>;",
    '  create(input: Omit<T, "id">): Promise<T>;',
    '  update(id: string, patch: Partial<Omit<T, "id">>): Promise<T>;',
    "  remove(id: string): Promise<void>;",
    "  /** Calls back on every change; returns the unsubscribe function. */",
    "  subscribe(listener: (items: T[]) => void): () => void;",
    "};",
    "",
    ...(plan.accounts
      ? [
          "export type Auth = {",
          "  currentUser(): Promise<User | null>;",
          "  signUp(email: string, password: string): Promise<User>;",
          "  signIn(email: string, password: string): Promise<User>;",
          "  signOut(): Promise<void>;",
          "  onChange(listener: (user: User | null) => void): () => void;",
          "};",
          "",
        ]
      : []),
    "export type ServerFunctions = {",
    ...fns.map(([n, f]) => `  /** ${f.purpose.replace(/\*\//g, "")} */\n  ${n}(input: Record<string, unknown>): Promise<Record<string, unknown>>;`),
    "};",
    "",
    "export type Backend = {",
    ...ents.map((e) => `  ${e.collection}: Collection<${e.type}>;`),
    ...(plan.accounts ? ["  auth: Auth;"] : []),
    "  functions: ServerFunctions;",
    "};",
    "",
  ].join("\n");

  const local = [
    "// In-memory backend: the app runs without a server (and the device checks pass).",
    "// Pass `persist` (e.g. AsyncStorage) to keep data on the device across restarts.",
    "",
    'import type { Backend, Collection } from "./adapter";',
    ...typeImport,
    "",
    "export type Persist = { getItem(key: string): Promise<string | null>; setItem(key: string, value: string): Promise<void> };",
    "",
    "let counter = 0;",
    "const newId = () => `${Date.now().toString(36)}-${(counter++).toString(36)}`;",
    "",
    "export function memoryCollection<T extends { id: string }>(name: string, persist?: Persist, seed: T[] = []): Collection<T> {",
    "  let items: T[] = [...seed];",
    "  let loaded: Promise<void> | null = null;",
    "  const listeners = new Set<(items: T[]) => void>();",
    "  const key = `backend:${name}`;",
    "  const load = () =>",
    "    (loaded ??= (async () => {",
    "      const raw = persist ? await persist.getItem(key) : null;",
    "      if (raw) items = JSON.parse(raw) as T[];",
    "    })());",
    "  const changed = async () => {",
    "    if (persist) await persist.setItem(key, JSON.stringify(items));",
    "    for (const l of listeners) l([...items]);",
    "  };",
    "  return {",
    "    async list() {",
    "      await load();",
    "      return [...items];",
    "    },",
    "    async get(id) {",
    "      await load();",
    "      return items.find((i) => i.id === id) ?? null;",
    "    },",
    "    async create(input) {",
    "      await load();",
    "      const item = { ...input, id: newId() } as T;",
    "      items = [...items, item];",
    "      await changed();",
    "      return item;",
    "    },",
    "    async update(id, patch) {",
    "      await load();",
    "      const cur = items.find((i) => i.id === id);",
    "      if (!cur) throw new Error(`Not found: ${id}`);",
    "      const next = { ...cur, ...patch } as T;",
    "      items = items.map((i) => (i.id === id ? next : i));",
    "      await changed();",
    "      return next;",
    "    },",
    "    async remove(id) {",
    "      await load();",
    "      items = items.filter((i) => i.id !== id);",
    "      await changed();",
    "    },",
    "    subscribe(listener) {",
    "      listeners.add(listener);",
    "      return () => {",
    "        listeners.delete(listener);",
    "      };",
    "    },",
    "  };",
    "}",
    "",
    "export function localBackend(o: { persist?: Persist } = {}): Backend {",
    ...(plan.accounts
      ? [
          "  let user: User | null = null;",
          "  const accounts = new Map<string, { user: User; password: string }>();",
          "  const authListeners = new Set<(u: User | null) => void>();",
          "  const setUser = (u: User | null) => {",
          "    user = u;",
          "    for (const l of authListeners) l(u);",
          "  };",
        ]
      : []),
    "  return {",
    ...ents.map((e) => `    ${e.collection}: memoryCollection<${e.type}>(${JSON.stringify(e.collection)}, o.persist),`),
    ...(plan.accounts
      ? [
          "    auth: {",
          "      async currentUser() {",
          "        return user;",
          "      },",
          "      async signUp(email, password) {",
          "        if (accounts.has(email)) throw new Error(\"There's already an account with this email.\");",
          "        const u: User = { id: newId(), email };",
          "        accounts.set(email, { user: u, password });",
          "        setUser(u);",
          "        return u;",
          "      },",
          "      async signIn(email, password) {",
          "        const a = accounts.get(email);",
          "        if (!a || a.password !== password) throw new Error(\"That email and password don't match.\");",
          "        setUser(a.user);",
          "        return a.user;",
          "      },",
          "      async signOut() {",
          "        setUser(null);",
          "      },",
          "      onChange(listener) {",
          "        authListeners.add(listener);",
          "        return () => {",
          "          authListeners.delete(listener);",
          "        };",
          "      },",
          "    },",
        ]
      : []),
    "    functions: {",
    ...fns.map(([n]) => `      async ${n}(input) {\n        // TODO(day2 build agent): what ${n} does, locally (no server yet).\n        return { ok: true, input };\n      },`),
    "    },",
    "  };",
    "}",
    "",
  ].join("\n");

  const hosted = o.hosted
    ? [
        "// The hosted backend: supabase-js against the app's Supabase project, run by day2.",
        "// TODO(day2 build agent): implement `Backend` (adapter.ts) here, one to one —",
        ...ents.map((e) => `//  - ${e.collection}: list/get/create/update/remove/subscribe for ${e.type} (${e.where === "server" ? "a table in supabase/migrations with row level security, rows owned by user_id = auth.uid() unless shared" : "kept on the device: reuse memoryCollection with persist"})`),
        ...(plan.accounts ? ["//  - auth: Supabase Auth; the session kept encrypted on the device (expo-secure-store + AsyncStorage)"] : []),
        ...fns.map(([n, f]) => `//  - functions.${n}: an edge function in supabase/functions/ — ${f.purpose.replace(/\n/g, " ")}`),
        "// The URL and the publishable key come from EXPO_PUBLIC_SUPABASE_URL and",
        "// EXPO_PUBLIC_SUPABASE_KEY (index.ts passes them in). Never a secret key.",
        "",
        'import type { Backend } from "./adapter";',
        "",
        "export type HostedConfig = { url: string; publicKey: string };",
        "",
        "export function hostedBackend(_config: HostedConfig): Backend {",
        '  throw new Error("The hosted backend isn\'t written yet.");',
        "}",
        "",
      ].join("\n")
    : [
        "// TODO: the hosted backend. This app keeps its data on the device for now. When",
        "// day2 hosts its backend (\"Host with day2\" on the app's Hosting page), day2",
        "// asks the build agent to implement `Backend` (adapter.ts) here on Supabase:",
        ...ents.map((e) => `//  - ${e.collection}: list/get/create/update/remove/subscribe for ${e.type} (${e.where === "server" ? "a server table, scoped to the signed-in user" : "kept on the device: reuse memoryCollection with persist"})`),
        ...(plan.accounts ? ["//  - auth: email sign-up/sign-in/sign-out, onChange; keep the session in expo-secure-store"] : []),
        ...fns.map(([n, f]) => `//  - functions.${n}: ${f.purpose.replace(/\n/g, " ")}`),
        "// Then index.ts picks it when EXPO_PUBLIC_SUPABASE_URL and _KEY are set. The screens don't change.",
        "// Don't add a provider SDK before that.",
        "",
        'import type { Backend } from "./adapter";',
        "",
        "export type HostedConfig = { url: string; publicKey: string };",
        "",
        "export function hostedBackend(_config: HostedConfig): Backend {",
        '  throw new Error("This app isn\'t hosted yet: its data stays on the device.");',
        "}",
        "",
      ].join("\n");

  const index = o.hosted
    ? [
        "// The app's backend: hosted (day2's Supabase project) when both public values are",
        "// set — day2 puts them in eas.json (store builds), EAS environment variables",
        "// (updates) and .env (development and device checks, against staging) — and in",
        "// memory in tests and without them.",
        "",
        'import { hostedBackend } from "./hosted";',
        'import { localBackend } from "./local";',
        'import type { Backend } from "./adapter";',
        "",
        "// Expo inlines EXPO_PUBLIC_ values at build time (typed here so this file needs no Node types).",
        "declare const process: { env: Record<string, string | undefined> };",
        "const url = process.env.EXPO_PUBLIC_SUPABASE_URL;",
        "const publicKey = process.env.EXPO_PUBLIC_SUPABASE_KEY;",
        "",
        'export const isHosted = Boolean(url && publicKey) && process.env.NODE_ENV !== "test";',
        "export const backend: Backend = isHosted ? hostedBackend({ url: url!, publicKey: publicKey! }) : localBackend();",
        'export type { Backend } from "./adapter";',
        'export * from "./types";',
        "",
      ].join("\n")
    : [
        "// The app's backend: in memory, on the device. When day2 hosts it, this switches",
        "// to hosted.ts when EXPO_PUBLIC_SUPABASE_URL and _KEY are set (see hosted.ts).",
        "",
        'import { localBackend } from "./local";',
        'import type { Backend } from "./adapter";',
        "",
        "export const backend: Backend = localBackend();",
        'export type { Backend } from "./adapter";',
        'export * from "./types";',
        "",
      ].join("\n");

  return { "src/backend/types.ts": types, "src/backend/adapter.ts": adapter, "src/backend/local.ts": local, "src/backend/hosted.ts": hosted, "src/backend/index.ts": index };
}
